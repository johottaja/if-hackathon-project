# Kirjoittaa paperin taulukot tiedostosta paperi/tulokset.csv kummallakin kielellä.
# Aja v0-kansiosta: Rscript paperi/kirjoita_taulukot.R (ei simuloi uudelleen).
source("R/simuloi_tammikuu.R")
source("paperi/asetelmat.R")

tulokset <- read.csv("paperi/tulokset.csv")
leveaksi <- function(d) {
  w <- reshape(d[, c("seed", "scenario", "expected_falls")], idvar = "seed",
               timevar = "scenario", direction = "wide")
  names(w) <- sub("expected_falls.", "", names(w), fixed = TRUE)
  w
}
kielet <- list(
  fi = list(desimaali = ",", erotin = "; ",
            nimet = c(ei_huoltoa = "ei\\_huoltoa", aikataulu = "aikataulu", kulku = "kulku",
                      tuote = "tuote", oraakkeli = "oraakkeli"),
            otsake = "%% Tuotettu: paperi/kirjoita_taulukot.R tiedostosta paperi/tulokset.csv, %d siementä."),
  en = list(desimaali = ".", erotin = ", ",
            nimet = c(ei_huoltoa = "no-grit", aikataulu = "rotation", kulku = "busiest",
                      tuote = "pito", oraakkeli = "oracle"),
            otsake = "%% Generated by paperi/kirjoita_taulukot.R from paperi/tulokset.csv, %d seeds.")
)

for (kieli in names(kielet)) {
  k <- kielet[[kieli]]
  luku <- function(x, d = 2) sub("^-", "$-$", formatC(x, format = "f", digits = d, decimal.mark = k$desimaali))
  valit <- function(x) {
    s <- 1.96 * sd(x) / sqrt(length(x))
    sprintf("%s \\,[%s%s%s]", luku(mean(x)), luku(mean(x) - s), k$erotin, luku(mean(x) + s))
  }
  w <- leveaksi(tulokset[tulokset$asetelma == 1, ])
  rivit <- vapply(politiikat, function(s) {
    ero <- w$kulku - w[[s]]
    sprintf("\\texttt{%s} & %s & %s & %s \\\\", k$nimet[[s]], valit(w[[s]]),
            luku(100 * (1 - mean(w[[s]]) / mean(w$ei_huoltoa)), 1),
            if (s == "kulku") "--" else valit(ero))
  }, character(1))
  writeLines(c(sprintf(k$otsake, nrow(w)), rivit), sprintf("paperi/taulukko_oletus_%s.tex", kieli))

  rivit <- vapply(seq_along(asetelmat), function(i) {
    w <- leveaksi(tulokset[tulokset$asetelma == i, ])
    ero <- w$kulku - w$tuote
    kuilu <- mean(w$kulku - w$oraakkeli)
    sprintf("%s & %d & %s & %s & %s & %s & %s & %s & %d & %s \\\\", asetelmat[[i]][[kieli]], nrow(w),
            luku(mean(w$ei_huoltoa), 1), luku(mean(w$aikataulu), 1), luku(mean(w$kulku), 1),
            luku(mean(w$tuote), 1), luku(mean(w$oraakkeli), 1), valit(ero), sum(ero > 0),
            if (kuilu > 1e-9) paste0(luku(100 * mean(ero) / kuilu, 0), " \\%") else "--")
  }, character(1))
  writeLines(c(sub(",[^,]*$", ".", sprintf(k$otsake, 0)), rivit), sprintf("paperi/taulukko_herkkyys_%s.tex", kieli))
}
message("Taulukot kirjoitettu (fi, en).")
